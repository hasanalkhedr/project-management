<?php

namespace App\Filament\Vitahr\Resources;

use App\Filament\Vitahr\Resources\AttendanceAttemptResource\Pages;
use App\Models\Vitahr\AttendanceAttempt;
use Filament\Forms;
use Filament\Resources\Resource;
use Filament\Tables;
use Filament\Tables\Table;

class AttendanceAttemptResource extends Resource
{
    protected static ?string $navigationGroup = 'نظام الحضور والتصراف';
    protected static ?string $model = AttendanceAttempt::class;

    protected static ?string $navigationIcon =
        'heroicon-o-shield-exclamation';

    protected static ?int $navigationSort = 6;

    /**
     * Attendance attempts are generated by the API.
     *
     * They must not be created manually from Filament.
     */
    public static function canCreate(): bool
    {
        return false;
    }

    public static function getNavigationLabel(): string
    {
        return __('vitahr.attendance_attempts');
    }

    public static function getModelLabel(): string
    {
        return __('vitahr.attendance_attempt');
    }

    public static function getPluralModelLabel(): string
    {
        return __('vitahr.attendance_attempts');
    }

    public static function table(Table $table): Table
    {
        return $table
            ->columns([
                /*
                 * Employee
                 */
                Tables\Columns\TextColumn::make(
                    'employee.employee_number'
                )
                    ->label(__('vitahr.employee_number'))
                    ->searchable()
                    ->sortable(),

                Tables\Columns\TextColumn::make(
                    'employee.user.name'
                )
                    ->label(__('vitahr.employee'))
                    ->searchable()
                    ->sortable(),

                /*
                 * Source
                 */
                Tables\Columns\TextColumn::make('attendance_event_id')
                    ->label(__('vitahr.source'))
                    ->formatStateUsing(
                        fn($state): string => $state
                            ? __('vitahr.offline')
                            : __('vitahr.online')
                    )
                    ->badge()
                    ->color(
                        fn($state): string => $state
                            ? 'warning'
                            : 'success'
                    )
                    ->sortable(),

                /*
                 * Client Event ID
                 *
                 * Only exists for offline attempts.
                 */
                Tables\Columns\TextColumn::make(
                    'attendanceEvent.client_event_id'
                )
                    ->label(__('vitahr.client_event_id'))
                    ->placeholder('-')
                    ->searchable()
                    ->copyable()
                    ->copyMessage(
                        __('vitahr.client_event_id_copied')
                    )
                    ->copyMessageDuration(1500)
                    ->toggleable(),

                /*
                 * Action
                 */
                Tables\Columns\TextColumn::make('action')
                    ->label(__('vitahr.action'))
                    ->badge()
                    ->formatStateUsing(
                        fn(?string $state): string =>
                            match ($state) {
                                'check_in' => __('vitahr.check_in'),
                                'check_out' => __('vitahr.check_out'),
                                default => $state
                                    ? ucfirst($state)
                                    : '-',
                            }
                    )
                    ->color(
                        fn(?string $state): string =>
                            match ($state) {
                                'check_in' => 'info',
                                'check_out' => 'warning',
                                default => 'gray',
                            }
                    )
                    ->sortable(),

                /*
                 * Result
                 */
                Tables\Columns\TextColumn::make('result')
                    ->label(__('vitahr.result'))
                    ->badge()
                    ->formatStateUsing(
                        fn(?string $state): string =>
                            match ($state) {
                                'accepted' => __('vitahr.accepted'),
                                'rejected' => __('vitahr.rejected'),
                                default => $state
                                    ? ucfirst($state)
                                    : '-',
                            }
                    )
                    ->color(
                        fn(?string $state): string =>
                            match ($state) {
                                'accepted' => 'success',
                                'rejected' => 'danger',
                                default => 'gray',
                            }
                    )
                    ->sortable(),

                /*
                 * Failure reason
                 */
                Tables\Columns\TextColumn::make(
                    'failure_reason'
                )
                    ->label(__('vitahr.failure_reason'))
                    ->placeholder('-')
                    ->limit(40)
                    ->tooltip(
                        fn(
                        ?AttendanceAttempt $record
                    ): ?string =>
                            $record?->failure_reason
                    )
                    ->toggleable(),

                /*
                 * Device identifier
                 */
                Tables\Columns\TextColumn::make(
                    'device_identifier'
                )
                    ->label(__('vitahr.device_identifier'))
                    ->searchable()
                    ->copyable()
                    ->copyMessage(
                        __('vitahr.device_identifier_copied')
                    )
                    ->copyMessageDuration(1500)
                    ->formatStateUsing(
                        fn(?string $state): string =>
                            $state
                            ? static::shortenDeviceIdentifier(
                                $state
                            )
                            : '-'
                    )
                    ->tooltip(
                        fn(
                        ?AttendanceAttempt $record
                    ): ?string =>
                            $record?->device_identifier
                    ),

                /*
                 * Accuracy
                 */
                Tables\Columns\TextColumn::make('accuracy')
                    ->label(__('vitahr.accuracy'))
                    ->suffix(' m')
                    ->sortable(),

                /*
                 * Attempt time
                 */
                Tables\Columns\TextColumn::make(
                    'created_at'
                )
                    ->label(__('vitahr.attempted_at'))
                    ->dateTime('Y-m-d H:i:s')
                    ->sortable(),
            ])

            ->filters([
                /*
                 * Employee
                 */
                Tables\Filters\SelectFilter::make(
                    'employee_id'
                )
                    ->label(__('vitahr.employee'))
                    ->relationship(
                        'employee',
                        'employee_number'
                    )
                    ->searchable()
                    ->preload(),

                /*
                 * Source
                 */
                Tables\Filters\SelectFilter::make(
                    'attendance_event_id'
                )
                    ->label(__('vitahr.source'))
                    ->options([
                        'online' => __('vitahr.online'),
                        'offline' => __('vitahr.offline'),
                    ])
                    ->query(
                        function ($query, array $data) {
                            return $query->when(
                                $data['value'] ?? null,
                                function ($query, $value) {
                                    if ($value === 'offline') {
                                        $query->whereNotNull(
                                            'attendance_event_id'
                                        );
                                    }

                                    if ($value === 'online') {
                                        $query->whereNull(
                                            'attendance_event_id'
                                        );
                                    }
                                }
                            );
                        }
                    ),

                /*
                 * Action
                 */
                Tables\Filters\SelectFilter::make('action')
                    ->label(__('vitahr.action'))
                    ->options([
                        'check_in' => __('vitahr.check_in'),
                        'check_out' => __('vitahr.check_out'),
                    ]),

                /*
                 * Result
                 */
                Tables\Filters\SelectFilter::make('result')
                    ->label(__('vitahr.result'))
                    ->options([
                        'accepted' => __('vitahr.accepted'),
                        'rejected' => __('vitahr.rejected'),
                    ]),

                /*
                 * Date range
                 */
                Tables\Filters\Filter::make('attempt_date')
                    ->label(__('vitahr.attempted_at'))
                    ->form([
                        Forms\Components\DatePicker::make('from')
                            ->label(__('vitahr.from')),

                        Forms\Components\DatePicker::make('until')
                            ->label(__('vitahr.until')),
                    ])
                    ->query(
                        function ($query, array $data) {
                            return $query
                                ->when(
                                    $data['from'] ?? null,
                                    fn(
                                    $query,
                                    $date
                                ) => $query->whereDate(
                                            'created_at',
                                            '>=',
                                            $date
                                        )
                                )
                                ->when(
                                    $data['until'] ?? null,
                                    fn(
                                    $query,
                                    $date
                                ) => $query->whereDate(
                                            'created_at',
                                            '<=',
                                            $date
                                        )
                                );
                        }
                    ),
            ])

            ->actions([
                Tables\Actions\Action::make('view')
                    ->label(__('vitahr.view'))
                    ->icon('heroicon-o-eye')
                    ->modalHeading(
                        __('vitahr.attendance_attempt')
                    )
                    ->modalSubmitAction(false)
                    ->modalCancelActionLabel(
                        __('vitahr.close')
                    )
                    ->form([
                        /*
                         * Employee
                         */
                        Forms\Components\Placeholder::make(
                            'employee'
                        )
                            ->label(__('vitahr.employee'))
                            ->content(
                                fn(
                                AttendanceAttempt $record
                            ): string =>
                                    $record->employee
                                            ?->employee_number
                                    . ' — '
                                    . (
                                        $record
                                            ->employee
                                            ?->user
                                                ?->name
                                        ?? '-'
                                    )
                            ),

                        /*
                         * Source
                         */
                        Forms\Components\Placeholder::make(
                            'source'
                        )
                            ->label(__('vitahr.source'))
                            ->content(
                                fn(
                                AttendanceAttempt $record
                            ): string =>
                                    $record->attendance_event_id
                                    ? __('vitahr.offline')
                                    : __('vitahr.online')
                            ),

                        /*
                         * Client Event ID
                         */
                        Forms\Components\Placeholder::make(
                            'client_event_id'
                        )
                            ->label(
                                __('vitahr.client_event_id')
                            )
                            ->content(
                                fn(
                                AttendanceAttempt $record
                            ): string =>
                                    $record->attendanceEvent
                                            ?->client_event_id
                                    ?? '-'
                            )
                            ->visible(
                                fn(
                                AttendanceAttempt $record
                            ): bool =>
                                    $record->attendance_event_id
                                    !== null
                            ),

                        /*
                         * Captured At
                         */
                        Forms\Components\Placeholder::make(
                            'captured_at'
                        )
                            ->label(
                                __('vitahr.captured_at')
                            )
                            ->content(
                                fn(
                                AttendanceAttempt $record
                            ): string =>
                                    $record->attendanceEvent
                                        ?->captured_at
                                            ?->format(
                                            'Y-m-d H:i:s'
                                        )
                                    ?? '-'
                            )
                            ->visible(
                                fn(
                                AttendanceAttempt $record
                            ): bool =>
                                    $record->attendance_event_id
                                    !== null
                            ),

                        /*
                         * Sync Status
                         */
                        Forms\Components\Placeholder::make(
                            'sync_status'
                        )
                            ->label(
                                __('vitahr.sync_status')
                            )
                            ->content(
                                fn(
                                AttendanceAttempt $record
                            ): string =>
                                    $record->attendanceEvent
                                        ?->sync_status?->value
                                    ?? '-'
                            )
                            ->visible(
                                fn(
                                AttendanceAttempt $record
                            ): bool =>
                                    $record->attendance_event_id
                                    !== null
                            ),

                        /*
                         * Action
                         */
                        Forms\Components\Placeholder::make(
                            'action'
                        )
                            ->label(__('vitahr.action'))
                            ->content(
                                fn(
                                AttendanceAttempt $record
                            ): string =>
                                    match ($record->action) {
                                        'check_in' =>
                                            __('vitahr.check_in'),

                                        'check_out' =>
                                            __('vitahr.check_out'),

                                        default =>
                                            $record->action
                                            ? ucfirst(
                                                str_replace(
                                                    '_',
                                                    '-',
                                                    $record->action
                                                )
                                            )
                                            : '-',
                                    }
                            ),

                        /*
                         * Result
                         */
                        Forms\Components\Placeholder::make(
                            'result'
                        )
                            ->label(__('vitahr.result'))
                            ->content(
                                fn(
                                AttendanceAttempt $record
                            ): string =>
                                    match ($record->result) {
                                        'accepted' =>
                                            __('vitahr.accepted'),

                                        'rejected' =>
                                            __('vitahr.rejected'),

                                        default =>
                                            $record->result
                                            ? ucfirst(
                                                $record->result
                                            )
                                            : '-',
                                    }
                            ),

                        /*
                         * Failure reason
                         */
                        Forms\Components\Placeholder::make(
                            'failure_reason'
                        )
                            ->label(
                                __('vitahr.failure_reason')
                            )
                            ->content(
                                fn(
                                AttendanceAttempt $record
                            ): string =>
                                    $record->failure_reason
                                    ?? __('vitahr.none')
                            ),

                        /*
                         * Location
                         */
                        Forms\Components\Placeholder::make(
                            'location'
                        )
                            ->label(__('vitahr.location'))
                            ->content(
                                fn(
                                AttendanceAttempt $record
                            ): string =>
                                    $record->latitude
                                    . ', '
                                    . $record->longitude
                            ),

                        /*
                         * Accuracy
                         */
                        Forms\Components\Placeholder::make(
                            'accuracy'
                        )
                            ->label(
                                __('vitahr.gps_accuracy')
                            )
                            ->content(
                                fn(
                                AttendanceAttempt $record
                            ): string =>
                                    $record->accuracy !== null
                                    ? $record->accuracy . ' m'
                                    : '-'
                            ),

                        /*
                         * Device identifier
                         */
                        Forms\Components\Placeholder::make(
                            'device_identifier'
                        )
                            ->label(
                                __('vitahr.device_identifier')
                            )
                            ->content(
                                fn(
                                AttendanceAttempt $record
                            ): string =>
                                    $record->device_identifier
                            ),

                        /*
                         * Attempted at
                         */
                        Forms\Components\Placeholder::make(
                            'attempted_at'
                        )
                            ->label(
                                __('vitahr.attempted_at')
                            )
                            ->content(
                                fn(
                                AttendanceAttempt $record
                            ): string =>
                                    $record->created_at
                                            ?->format(
                                            'Y-m-d H:i:s'
                                        )
                                    ?? '-'
                            ),
                    ]),
            ])

            ->bulkActions([])

            ->defaultSort(
                'created_at',
                'desc'
            );
    }

    protected static function shortenDeviceIdentifier(
        string $identifier
    ): string {
        $length = strlen($identifier);

        if ($length <= 16) {
            return $identifier;
        }

        return substr($identifier, 0, 8)
            . '...'
            . substr($identifier, -8);
    }

    public static function getRelations(): array
    {
        return [];
    }

    public static function getPages(): array
    {
        return [
            'index' => Pages\ListAttendanceAttempts::route('/'),
        ];
    }
}
